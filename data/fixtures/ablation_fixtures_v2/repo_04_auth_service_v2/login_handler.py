"""Authentication handler module executing user verification (v2 - Hardened)."""

from __future__ import annotations

import hashlib
import hmac
import secrets
from typing import Any

from rate_limiter import SlidingWindowRateLimiter

# Explicit input length limits to prevent denial-of-service via oversized payloads
MAX_USERNAME_LENGTH: int = 256
MAX_PASSWORD_LENGTH: int = 4096

# Minimum salt size per NIST SP 800-63B Rev 4 (at least 32 bits / 4 bytes).
# Standard practice uses 128 bits (16 bytes = 32 hex chars) to minimize collision risk.
MIN_SALT_BYTES: int = 16
MIN_SALT_HEX_LENGTH: int = 8  # 32 bits = 4 bytes = 8 hex characters

# Current OWASP Password Storage recommendation for PBKDF2-HMAC-SHA256 (600,000 iterations for FIPS-140 compliance)
DEFAULT_PBKDF2_ITERATIONS: int = 600_000


HEX_DIGITS: frozenset[str] = frozenset("0123456789abcdefABCDEF")


def generate_salt(num_bytes: int = MIN_SALT_BYTES) -> str:
    """Generate cryptographically secure random salt using CSPRNG.

    Conforms to NIST SP 800-63B Rev 4 requirements for unique, collision-resistant salts
    chosen from a high-entropy random source. The `num_bytes` argument controls the number
    of random bytes generated. Returns a hexadecimal string of length `2 * num_bytes`.
    """
    if not isinstance(num_bytes, int) or num_bytes < 4:
        raise ValueError("Salt size must be an integer of at least 4 bytes (32 bits) per NIST SP 800-63B Rev 4")
    return secrets.token_hex(num_bytes)


def validate_salt(salt: str) -> None:
    """Validate that salt is a valid hexadecimal string meeting minimum length criteria.

    Per NIST SP 800-63B Rev 4 (Section 3.1.1.2), salt must be at least 32 bits (4 bytes = 8 hex chars).
    Rejects non-string values, empty strings, values shorter than 8 hex characters, odd-length strings,
    whitespace, and non-hexadecimal characters.
    """
    if not isinstance(salt, str):
        raise ValueError("Salt must be a string")
    if len(salt) < MIN_SALT_HEX_LENGTH:
        raise ValueError(
            f"Salt must contain at least {MIN_SALT_HEX_LENGTH} characters "
            f"(at least 32 bits of entropy per NIST SP 800-63B Rev 4)"
        )
    if len(salt) % 2 != 0:
        raise ValueError(
            f"Salt hex string must have an even length (got {len(salt)} chars), "
            f"as each byte requires exactly two hexadecimal digits"
        )
    if not all(c in HEX_DIGITS for c in salt):
        raise ValueError("Salt must contain only valid hexadecimal characters [0-9a-fA-F]")
    try:
        bytes.fromhex(salt)
    except ValueError as err:
        raise ValueError(f"Salt must contain only valid hexadecimal characters [0-9a-fA-F]: {err}") from err


def create_credential_record(
    password: str,
    *,
    num_salt_bytes: int = MIN_SALT_BYTES,
    iterations: int = DEFAULT_PBKDF2_ITERATIONS,
) -> dict[str, Any]:
    """Create a structured credential record storing hash, fresh random salt, and scheme metadata.

    The normal credential-creation path ALWAYS generates a fresh, cryptographically secure
    random salt via CSPRNG (`generate_salt(num_salt_bytes)`). Callers cannot provide fixed,
    predictable, or reused salts through this interface.

    Stores the algorithm scheme, iteration cost factor, salt, and derived hash to support
    future algorithm and parameter migration per NIST SP 800-63B Rev 4.
    """
    if not isinstance(password, str) or len(password) > MAX_PASSWORD_LENGTH:
        raise ValueError(f"Password must be a string up to {MAX_PASSWORD_LENGTH} characters")

    fresh_salt = generate_salt(num_bytes=num_salt_bytes)
    validate_salt(fresh_salt)

    derived = hashlib.pbkdf2_hmac(
        "sha256",
        password.encode("utf-8"),
        fresh_salt.encode("utf-8"),
        iterations=iterations,
    ).hex()

    return {
        "scheme": "pbkdf2_hmac_sha256",
        "iterations": iterations,
        "salt": fresh_salt,
        "hash": derived,
    }


def import_legacy_credential_record(
    password: str,
    salt: str,
    *,
    iterations: int = DEFAULT_PBKDF2_ITERATIONS,
) -> dict[str, Any]:
    """Import or reconstruct an existing credential record using an externally supplied salt.

    CALLER SECURITY CONTRACT:
    This function is strictly for migrating or importing pre-existing credentials.
    The caller MUST guarantee that:
    1. The supplied salt was originally generated by a cryptographically secure random source (CSPRNG).
    2. The salt is unique per credential (minimizing collision risk; standard is >= 128 bits).
    3. The salt is persisted alongside the hash in durable storage.
    4. Minimum entropy of at least 32 bits (8 hex characters) is satisfied.
    """
    if not isinstance(password, str) or len(password) > MAX_PASSWORD_LENGTH:
        raise ValueError(f"Password must be a string up to {MAX_PASSWORD_LENGTH} characters")

    validate_salt(salt)

    derived = hashlib.pbkdf2_hmac(
        "sha256",
        password.encode("utf-8"),
        salt.encode("utf-8"),
        iterations=iterations,
    ).hex()

    return {
        "scheme": "pbkdf2_hmac_sha256",
        "iterations": iterations,
        "salt": salt,
        "hash": derived,
    }


def verify_credential_record(
    record: dict[str, Any],
    password_attempt: str,
    limiter: SlidingWindowRateLimiter,
    username: str | None = None,
) -> bool:
    """Verify a password attempt against a structured credential record.

    Uses the algorithm scheme, iteration count, and salt recorded in `record`,
    rather than silently relying on ambient module defaults that may change over time.
    """
    if not isinstance(record, dict):
        raise ValueError("Credential record must be a dictionary")

    scheme = record.get("scheme")
    if scheme != "pbkdf2_hmac_sha256":
        raise ValueError(f"Unsupported credential scheme: {scheme}")

    iterations = record.get("iterations")
    if not isinstance(iterations, int) or iterations < 1:
        raise ValueError(f"Invalid iteration count in record: {iterations}")

    salt = record.get("salt")
    stored_hash = record.get("hash")
    if not isinstance(stored_hash, str):
        raise ValueError("Invalid hash in record")

    auth_key = username or f"salt:{salt}"
    return process_login_attempt(
        username=auth_key,
        password_attempt=password_attempt,
        stored_hash=stored_hash,
        salt=salt,
        limiter=limiter,
        iterations=iterations,
    )


def check_needs_rehash(
    record: dict[str, Any],
    target_scheme: str = "pbkdf2_hmac_sha256",
    target_iterations: int = DEFAULT_PBKDF2_ITERATIONS,
) -> bool:
    """Check if a credential record requires re-hashing to upgraded parameters upon successful authentication.

    Supports safe future work-factor or algorithm migration without misinterpreting older records.
    """
    if record.get("scheme") != target_scheme:
        return True
    if record.get("iterations", 0) < target_iterations:
        return True
    return False


def process_login_attempt(
    username: str,
    password_attempt: str,
    stored_hash: str,
    salt: str,
    limiter: SlidingWindowRateLimiter,
    iterations: int = DEFAULT_PBKDF2_ITERATIONS,
) -> bool:
    """Verify login credentials with explicit rate limit protection, input bounds, and salt validation.

    1. Enforces input length bounds to reject oversized strings before cryptographic operations.
    2. Enforces minimum salt length and hexadecimal validity per NIST SP 800-63B Rev 4.
    3. Enforces sliding-window rate limiting on the account key to prevent single-target brute-force attacks.
    4. Computes salted PBKDF2-HMAC-SHA256 hash using the specified iteration work factor.
    5. Compares derived hash against stored hash in constant time via `hmac.compare_digest`.
    """
    # 1. Input length validation to prevent CPU/memory exhaustion on malformed requests
    if not isinstance(username, str) or len(username) > MAX_USERNAME_LENGTH:
        raise ValueError(f"Username must be a string up to {MAX_USERNAME_LENGTH} characters")

    if not isinstance(password_attempt, str) or len(password_attempt) > MAX_PASSWORD_LENGTH:
        raise ValueError(f"Password attempt must be a string up to {MAX_PASSWORD_LENGTH} characters")

    # 2. Validate salt format and entropy
    validate_salt(salt)

    # 3. Rate limiting check (halt immediately if threshold breached)
    limiter.check_and_record(key=f"auth:{username}")

    # 4. Compute salted hash
    derived = hashlib.pbkdf2_hmac(
        "sha256",
        password_attempt.encode("utf-8"),
        salt.encode("utf-8"),
        iterations=iterations,
    ).hex()

    # 5. Constant-time digest comparison
    return hmac.compare_digest(derived, stored_hash)
